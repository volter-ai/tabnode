/**
 * `internalBinding('modules')` where the realm's process is `node` (ADR-0018 §7): Node v24.21.0's src/node_modules.cc
 * split where V8 stands, for Node's own `internal/modules/package_json_reader`, `helpers`, `run_main` and
 * `esm/resolve`. A package.json is read through the process's fs binding (libuv's `uv_fs_*`, item 6), parsed, kept per
 * path as BindingData's `package_configs_`, and answered as PackageConfig::Serialize answers it: `[name, main, type,
 * imports, exports, filePath]`, `exports` and `imports` the JSON text of an object or an array, else the string.
 *
 * Where this differs from Node: the compile cache is V8's code cache, which a page's engine does not make, so
 * `enableCompileCache` answers DISABLED and no entry is ever found; simdjson's raw text of `exports` and `imports` is
 * their JSON as `JSON.stringify` writes it again, the same value.
 */

/** COMPILE_CACHE_STATUS (src/compile_cache.h). */
const COMPILE_CACHE_STATUS = ['FAILED', 'ENABLED', 'ALREADY_ENABLED', 'DISABLED'];
/** CACHED_CODE_TYPES (src/compile_cache.h). */
const CACHED_CODE_TYPES = { kCommonJS: 0, kESM: 1, kStrippedTypeScript: 2, kTransformedTypeScript: 3, kTransformedTypeScriptWithSourceMaps: 4 };

interface PackageConfig {
  name?: string; main?: string; type: string; imports?: string; exports?: string; filePath: string;
}

/** std::filesystem::path::parent_path of an absolute POSIX path. */
function parentPath(path: string): string {
  if (path.endsWith('/') && path.length > 1) return path.slice(0, -1);
  const at = path.lastIndexOf('/');
  return at <= 0 ? '/' : path.slice(0, at);
}

export function createNodeModulesBinding(require: (id: string) => any, fs: () => { readFileUtf8(path: string, flags: number): string }): Record<string, unknown> {
  const configs = new Map<string, PackageConfig | null>();
  const codes = (): Record<string, new (...args: unknown[]) => Error> => (require('internal/errors') as { codes: Record<string, new (...args: unknown[]) => Error> }).codes;
  const invalid = (message: string): Error => {
    const error = new (codes().ERR_INVALID_PACKAGE_CONFIG!)('');
    error.message = message;
    return error;
  };
  /** BindingData::GetPackageJSON: the config at `path`, null where there is no file, an error where it is invalid. */
  const getPackageJSON = (path: string, context?: { base?: string; specifier: string }): PackageConfig | null => {
    if (configs.has(path)) return configs.get(path)!;
    let raw: string;
    try { raw = fs().readFileUtf8(path, 0); }
    catch (error) {
      const code = (error as { code?: unknown }).code;
      if (code !== 'ENOENT' && code !== 'ENOTDIR' && code !== 'EISDIR') {
        throw invalid(`Cannot read package config ${path}: ${(error as Error).message}.`);
      }
      configs.set(path, null);
      return null;
    }
    const failed = (): Error => {
      if (context?.base !== undefined) {
        const from = (require('internal/url') as { fileURLToPath(url: string): string }).fileURLToPath(context.base);
        return invalid(`Invalid package config ${path} while importing "${context.specifier}" from ${from}.`);
      }
      return invalid(`Invalid package config ${path}.`);
    };
    let document: unknown;
    // simdjson skips a UTF-8 byte order mark (node_modules.cc:114), which JSON.parse does not.
    try { document = JSON.parse(raw.charCodeAt(0) === 0xfeff ? raw.slice(1) : raw); } catch { throw failed(); }
    if (document === null || typeof document !== 'object' || Array.isArray(document)) throw failed();
    const config: PackageConfig = { type: 'none', filePath: path };
    const fields = document as Record<string, unknown>;
    for (const key of Object.keys(fields)) {
      const value = fields[key];
      if (key === 'name') {
        if (typeof value !== 'string') throw failed();
        config.name = value;
      } else if (key === 'main') {
        if (typeof value === 'string') config.main = value;
      } else if (key === 'exports' || key === 'imports') {
        if (value !== null && typeof value === 'object') config[key] = JSON.stringify(value);
        else if (typeof value === 'string') config[key] = value;
      } else if (key === 'type') {
        if (typeof value !== 'string') throw failed();
        if (value === 'commonjs' || value === 'module') config.type = value;
      }
    }
    configs.set(path, config);
    return config;
  };
  const serialize = (config: PackageConfig): unknown[] => [config.name, config.main, config.type, config.imports, config.exports, config.filePath];
  /** BindingData::TraverseParent: the nearest package.json above `check`, never past a `node_modules`. */
  const traverseParent = (check: string): PackageConfig | null => {
    let current = check;
    for (;;) {
      current = parentPath(current);
      if (parentPath(current) === current) return null;
      if (current.slice(current.lastIndexOf('/') + 1) === 'node_modules') return null;
      const found = getPackageJSON(`${current === '/' ? '' : current}/package.json`);
      if (found !== null) return found;
    }
  };
  const string = (value: unknown, name: string): string => {
    if (typeof value !== 'string') throw new TypeError(`modules.${name}: a string`);
    return value;
  };
  /** BindingData::GetPackageScopeConfig: up from `resolved`'s package.json URL to a root or a `node_modules`. */
  const packageScope = (resolved: string, onlyType: boolean): unknown => {
    const { fileURLToPath } = require('internal/url') as { fileURLToPath(url: URL): string };
    let url: URL;
    try { url = new URL('./package.json', new URL(resolved)); }
    catch { throw new (codes().ERR_INVALID_URL!)(resolved); }
    for (;;) {
      if (url.pathname.endsWith('/node_modules/package.json')) break;
      const found = getPackageJSON(fileURLToPath(url), { specifier: resolved });
      if (found !== null) return onlyType ? found.type : serialize(found);
      const last = url.pathname;
      url = new URL('../package.json', url);
      if (url.pathname === last) break;
    }
    if (onlyType) return undefined;
    return fileURLToPath(url);
  };
  return {
    readPackageJSON(path: unknown, isESM?: unknown, base?: unknown, specifier?: unknown): unknown[] | undefined {
      const context = isESM === true ? { ...(typeof base === 'string' ? { base } : {}), specifier: String(specifier) } : undefined;
      const found = getPackageJSON(string(path, 'readPackageJSON'), context);
      return found === null ? undefined : serialize(found);
    },
    getNearestParentPackageJSON(path: unknown): unknown[] | undefined {
      const found = traverseParent(string(path, 'getNearestParentPackageJSON'));
      return found === null ? undefined : serialize(found);
    },
    getNearestParentPackageJSONType(path: unknown): string | undefined {
      return traverseParent(string(path, 'getNearestParentPackageJSONType'))?.type;
    },
    getPackageScopeConfig: (resolved: unknown): unknown => packageScope(string(resolved, 'getPackageScopeConfig'), false),
    getPackageType: (resolved: unknown): unknown => packageScope(string(resolved, 'getPackageType'), true),
    enableCompileCache(cacheDir: unknown): unknown[] {
      if (typeof cacheDir !== 'string') throw new (codes().ERR_INVALID_ARG_TYPE!)('cacheDir should be a string');
      return [COMPILE_CACHE_STATUS.indexOf('DISABLED'), "V8's code cache is not a page's engine's to make", ''];
    },
    getCompileCacheDir: (): string => '',
    flushCompileCache(keep?: unknown): void {
      if (keep !== undefined && typeof keep !== 'boolean') throw new (codes().ERR_INVALID_ARG_TYPE!)('keepDeserializedCache should be a boolean');
    },
    getCompileCacheEntry: (): undefined => undefined,
    saveCompileCacheEntry(): never {
      throw new Error('modules.saveCompileCacheEntry: the compile cache is not enabled');
    },
    // InitImportMetaPathHelpers: `dirname` and `filename` of a file URL, each made on its first read.
    setLazyPathHelpers(target: object, url: string): void {
      const file = (): string => (require('internal/url') as { fileURLToPath(url: string): string }).fileURLToPath(url);
      for (const name of ['dirname', 'filename']) {
        Object.defineProperty(target, name, {
          configurable: true, enumerable: true,
          get() {
            const path = file();
            const value = name === 'dirname' ? path.slice(0, path.lastIndexOf('/')) : path;
            Object.defineProperty(target, name, { value, writable: true, enumerable: true, configurable: true });
            return value;
          },
        });
      }
    },
    compileCacheStatus: [...COMPILE_CACHE_STATUS],
    cachedCodeTypes: Object.freeze({ __proto__: null, ...CACHED_CODE_TYPES }),
    moduleFormats: Object.freeze({ __proto__: null, kCommonJS: 0, kModule: 1 }),
  };
}
